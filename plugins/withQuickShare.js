// Expo config plugin: adds a "share target" to the Android app that does NOT open the app.
//
// When you tap Share on a screenshot and pick "Anime Inbox", a tiny invisible activity copies the
// image into the app's private folder (files/inbox), shows a short "Saved" message and closes.
// The app picks the copies up the next time it runs (or in its background task).
//
// Because the copy is made immediately, it does not matter if the phone deletes the original
// screenshot right after sharing.
const { withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const ACTIVITY = 'QuickShareActivity';

function kotlinSource(pkg) {
  return `package ${pkg}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.os.Bundle
import android.widget.Toast
import java.io.File

// Generated by plugins/withQuickShare.js - receives shared images and saves a private copy.
class ${ACTIVITY} : Activity() {

  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    var saved = 0
    try {
      val dir = File(filesDir, "inbox")
      if (!dir.exists()) dir.mkdirs()
      val uris = collectUris(intent)
      for (uri in uris) {
        try {
          val mime = contentResolver.getType(uri) ?: "image/jpeg"
          val ext = when {
            mime.contains("png") -> "png"
            mime.contains("webp") -> "webp"
            else -> "jpg"
          }
          val target = File(dir, "shared_" + System.currentTimeMillis() + "_" + saved + "." + ext)
          val input = contentResolver.openInputStream(uri)
          if (input != null) {
            input.use { ins -> target.outputStream().use { outs -> ins.copyTo(outs) } }
            saved++
          }
        } catch (e: Exception) {
          // skip this image, try the next one
        }
      }
    } catch (e: Exception) {
      // nothing to do - the toast below reports the failure
    }

    // The app writes an empty file called "toast_off" when the user turns the message off.
    val toastOff = File(filesDir, "toast_off").exists()
    if (!toastOff) {
      val msg = when {
        saved == 1 -> "Saved to your anime inbox"
        saved > 1 -> "Saved " + saved + " to your anime inbox"
        else -> "Couldn't save that image"
      }
      Toast.makeText(applicationContext, msg, Toast.LENGTH_SHORT).show()
    }
    finish()
  }

  @Suppress("DEPRECATION")
  private fun collectUris(intent: Intent?): List<Uri> {
    val out = ArrayList<Uri>()
    if (intent == null) return out
    if (Intent.ACTION_SEND == intent.action) {
      val u: Uri? = if (Build.VERSION.SDK_INT >= 33) {
        intent.getParcelableExtra(Intent.EXTRA_STREAM, Uri::class.java)
      } else {
        intent.getParcelableExtra<Uri>(Intent.EXTRA_STREAM)
      }
      if (u != null) out.add(u)
    } else if (Intent.ACTION_SEND_MULTIPLE == intent.action) {
      val list: ArrayList<Uri>? = if (Build.VERSION.SDK_INT >= 33) {
        intent.getParcelableArrayListExtra(Intent.EXTRA_STREAM, Uri::class.java)
      } else {
        intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM)
      }
      if (list != null) out.addAll(list)
    }
    return out
  }
}
`;
}

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const pkg = cfg.android && cfg.android.package;
    if (!pkg) throw new Error('withQuickShare: set expo.android.package in app.json');
    const app = cfg.modResults.manifest.application[0];
    app.activity = app.activity || [];
    const fullName = pkg + '.' + ACTIVITY;
    const exists = app.activity.some((a) => a.$ && a.$['android:name'] === fullName);
    if (!exists) {
      app.activity.push({
        $: {
          'android:name': fullName,
          'android:exported': 'true',
          'android:label': 'Anime Inbox',
          'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
          'android:excludeFromRecents': 'true',
          'android:noHistory': 'true',
          'android:taskAffinity': '',
        },
        'intent-filter': [
          {
            action: [{ $: { 'android:name': 'android.intent.action.SEND' } }],
            category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
            data: [{ $: { 'android:mimeType': 'image/*' } }],
          },
          {
            action: [{ $: { 'android:name': 'android.intent.action.SEND_MULTIPLE' } }],
            category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
            data: [{ $: { 'android:mimeType': 'image/*' } }],
          },
        ],
      });
    }
    return cfg;
  });
}

function withKotlinFile(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android && cfg.android.package;
      if (!pkg) throw new Error('withQuickShare: set expo.android.package in app.json');
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, ACTIVITY + '.kt'), kotlinSource(pkg));
      return cfg;
    },
  ]);
}

module.exports = function withQuickShare(config) {
  config = withManifest(config);
  config = withKotlinFile(config);
  return config;
};
